function paragraph(text: string) {
  return {
    type: 'paragraph' as const,
    children: [
      {
        type: 'text' as const,
        detail: 0,
        format: 0,
        mode: 'normal' as const,
        style: '',
        text,
        version: 1 as const,
      },
    ],
    direction: 'ltr' as const,
    format: '' as const,
    indent: 0,
    textFormat: 0,
    version: 1 as const,
  }
}

export function createSeedPost({
  title,
  slug,
  excerpt,
  readingTime,
  categoryIds,
  heroImage,
  author,
  publishedAt,
  featured = false,
  featuredOrder = 0,
  breakingNews = false,
  editorsPick = false,
  editorsPickOrder = 0,
  viewCount,
}: SeedPostInput): RequiredDataFromCollectionSlug<'posts'> {
  return {
    title,
    slug,
    _status: 'published',
    authors: [author],
    categories: categoryIds,
    excerpt,
    readingTime,
    viewCount,
    featured,
    featuredOrder,
    breakingNews,
    editorsPick,
    editorsPickOrder,
    publishedAt,
    heroImage: heroImage.id,
    content: {
      root: {
        type: 'root',
        children: [paragraph(excerpt), ...LOREM_IPSUM_PARAGRAPHS.map(paragraph)],
        direction: 'ltr',
        format: '',
        indent: 0,
        version: 1,
      },
    },
    meta: {
      title,
      description: excerpt,
      image: heroImage.id,
    },
    relatedPosts: [],
  }
}
